// Make the runtime PotionSidebarUI's own Bag hierarchy visible and editable
// in the ACTUAL Stage1/Stage2 HUDs and the shared Stage3/Stage4 HUD prefab.
// No new inventory, consumables, controllers or duplicate runtime canvases.
// Executed only from a visible Unity Editor menu with preflight + backup.
#if UNITY_EDITOR
using System;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.SceneManagement;
using UnityEngine.UI;

internal static class OfficialPotionBagEditModePromotion
{
    private const string Stage1 = "Assets/Scenes/SampleScene.unity";
    private const string Stage2 = "Assets/Scenes/Stage2Scene/Stage2Scene.unity";
    private const string Stage3 = "Assets/Scenes/Stage3Scene/Stage3Scene.unity";
    private const string Stage4 = "Assets/Scenes/Stage4Scene/Stage4Scene.unity";
    private const string SharedPrefab = "Assets/Prefabs/PersistentGameplayHUD.prefab";
    private const string BackupDir = "Library/GameplayHudEditModeParity_20261021/OfficialBagAuthoringBefore";

    [MenuItem("SPELLSTRIKE/HUD & Potion/Make Bag Visible in Stage 1-4 Edit Mode (Official)")]
    private static void Promote()
    {
        Scene original = SceneManager.GetActiveScene();
        if (EditorApplication.isPlayingOrWillChangePlaymode ||
            !original.IsValid() || !original.isLoaded || original.isDirty ||
            SceneManager.sceneCount != 1 || Directory.Exists(BackupDir))
        {
            Debug.LogError("[Official Bag] Stop Play, SAVE current Editor scene, and ensure no previous integration attempt.");
            return;
        }

        Scene scene1 = default, scene2 = default;
        GameObject prefabRoot = null;
        try
        {
            string[] files = { Stage1, Stage2, Stage3, Stage4, SharedPrefab };
            foreach (string file in files)
                if (!File.Exists(file))
                    throw new FileNotFoundException("Missing production HUD resource: " + file);
            scene1 = original.path == Stage1
                ? original : EditorSceneManager.OpenScene(Stage1, OpenSceneMode.Additive);
            scene2 = original.path == Stage2
                ? original : EditorSceneManager.OpenScene(Stage2, OpenSceneMode.Additive);
            if (scene1.isDirty || scene2.isDirty)
                throw new InvalidOperationException("Stage1 or Stage2 has unsaved changes.");

            Transform root1 = FindHud(scene1), root2 = FindHud(scene2);
            prefabRoot = PrefabUtility.LoadPrefabContents(SharedPrefab);
            Canvas canvas1 = CombatCanvas(root1), canvas2 = CombatCanvas(root2);
            Canvas canvasShared = CombatCanvas(prefabRoot.transform);
            if (canvas1.transform.Find("PotionSidebarUI_AutoGenerated") != null ||
                canvas2.transform.Find("PotionSidebarUI_AutoGenerated") != null ||
                canvasShared.transform.Find("PotionSidebarUI_AutoGenerated") != null)
                throw new InvalidOperationException("A serialized Bag already exists. Never author a duplicate.");
            // Confirm we will add exactly one Bag component to each canonical
            // combat Canvas and not modify Stage2's separate legacy sidebar.
            foreach (Canvas canvas in new[] { canvas1, canvas2, canvasShared })
                if (canvas.GetComponents<PotionSidebarUI>().Length > 1)
                    throw new InvalidOperationException("Multiple PotionSidebarUI components already exist on combat Canvas.");

            // Backup BEFORE modifying any target. Protect identifiers and
            // progression/reference config as well as the three edited assets.
            foreach (string file in files.Concat(new[] { "ProjectSettings/EditorBuildSettings.asset" }))
            {
                string backup = BackupDir + "/" + file;
                Directory.CreateDirectory(Path.GetDirectoryName(backup));
                File.Copy(file, backup, false);
                string meta = file + ".meta";
                if (File.Exists(meta))
                    File.Copy(meta, backup + ".meta", false);
            }

            Author(canvas1);
            Author(canvas2);
            Author(canvasShared);
            Check(canvas1);
            Check(canvas2);
            Check(canvasShared);

            PrefabUtility.SaveAsPrefabAsset(prefabRoot, SharedPrefab);
            EditorSceneManager.MarkSceneDirty(scene1);
            EditorSceneManager.MarkSceneDirty(scene2);
            if (!EditorSceneManager.SaveScene(scene1, Stage1) ||
                !EditorSceneManager.SaveScene(scene2, Stage2))
                throw new IOException("Cannot save both official Bag-authored gameplay scenes.");

            Debug.Log("[Official Bag] PASS: Saved one identical, actual Potion Bag presentation in Stage1 and Stage2 scene HUDs plus Stage3/4 shared HUD prefab. Existing inventory, potion consumption, gameplay managers and all other scenes untouched. Full backup: " + BackupDir);
            SceneView.RepaintAll();
        }
        catch (Exception exception)
        {
            Debug.LogException(exception);
            Debug.LogError("[Official Bag] Stopped; inspect the backup and current assets for partial saves. Do NOT blindly rerun.");
        }
        finally
        {
            if (prefabRoot != null) PrefabUtility.UnloadPrefabContents(prefabRoot);
            if (scene2.IsValid() && scene2.isLoaded && scene2 != original)
                EditorSceneManager.CloseScene(scene2, true);
            if (scene1.IsValid() && scene1.isLoaded && scene1 != original)
                EditorSceneManager.CloseScene(scene1, true);
        }
    }

    private static Transform FindHud(Scene scene)
    {
        Transform[] roots = scene.GetRootGameObjects()
            .SelectMany(go => go.GetComponentsInChildren<Transform>(true))
            .Where(t => t.name == "PersistentHUDRoot").ToArray();
        if (roots.Length != 1)
            throw new InvalidOperationException("Expected one existing HUD in " + scene.path);
        return roots[0];
    }

    private static Canvas CombatCanvas(Transform hud)
    {
        var attacks = hud.GetComponentsInChildren<Button>(true)
            .Where(button => button.name == "AttackButton").ToArray();
        if (attacks.Length != 1)
            throw new InvalidOperationException("Expected one original attack Button in " + hud.name);
        Canvas canvas = attacks[0].GetComponentInParent<Canvas>(true);
        if (canvas == null || canvas.GetComponent<GraphicRaycaster>() == null)
            throw new InvalidOperationException("Original combat Canvas must have an active GraphicRaycaster.");
        return canvas;
    }

    private static void Author(Canvas canvas)
    {
        PotionSidebarUI sidebar = canvas.GetComponent<PotionSidebarUI>();
        if (sidebar == null)
            sidebar = canvas.gameObject.AddComponent<PotionSidebarUI>();
        sidebar.AuthorEditModeBag(canvas);
    }

    private static void Check(Canvas canvas)
    {
        Transform root = canvas.transform.Find("PotionSidebarUI_AutoGenerated");
        if (root == null ||
            root.Find("PotionBagButton")?.GetComponent<Button>() == null ||
            root.Find("BagFlyout/PotionRow/HPotionSlot")?.GetComponent<Button>() == null ||
            root.Find("BagFlyout/PotionRow/PPotionSlot")?.GetComponent<Button>() == null ||
            root.Find("BagFlyout/PotionRow/UPotionSlot")?.GetComponent<Button>() == null ||
            root.Find("BagFlyout/PassiveRow/Slot1PassiveSlot") == null ||
            root.Find("BagFlyout/PassiveRow/Slot2PassiveSlot") == null ||
            root.Find("BagFlyout/PassiveRow/Slot3PassiveSlot") == null ||
            root.Find("BagTooltip") == null ||
            root.Find("BagFlyout").gameObject.activeSelf)
            throw new InvalidOperationException("Bag authoring hierarchy/closed-state check failed.");
    }
}
#endif
