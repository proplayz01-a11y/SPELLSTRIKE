        LayoutElement layout = header.gameObject.AddComponent<LayoutElement>();
        layout.minHeight = 96f;
        layout.preferredHeight = 96f;

        TextMeshProUGUI title = CreateText(header, "Title", "SPELLSTRIKE - PREPARE YOUR LOADOUT", 38f, FontStyles.Bold, textColor);
        RectTransform titleRect = title.GetComponent<RectTransform>();
        titleRect.anchorMin = Vector2.zero;
        titleRect.anchorMax = Vector2.one;
        titleRect.offsetMin = new Vector2(24f, 0f);
        titleRect.offsetMax = new Vector2(-24f, 0f);
        title.alignment = TextAlignmentOptions.Center;
    }

