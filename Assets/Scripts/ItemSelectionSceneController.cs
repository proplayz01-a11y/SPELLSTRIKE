        layout.preferredHeight = 80f;

        TextMeshProUGUI text = CreateText(slot, "Text", "Slot " + slotNumber + "\nEmpty", 18f, FontStyles.Bold, textColor);
        RectTransform textRect = text.GetComponent<RectTransform>();
